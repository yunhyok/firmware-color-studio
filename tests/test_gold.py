"""Firmware-free regressions from independently executed original ARM output."""
from hashlib import sha256
import json
from pathlib import Path

import numpy as np
import pytest

from firmware_color_studio.engine import Engine
from firmware_color_studio.gold import _calculate, _hardware, _interpolate, gold_camera, runtime_spec

DATA = Path(__file__).resolve().parents[1] / 'src/firmware_color_studio/data/k3iii'
RECORD = json.loads((DATA / 'gold-verification.json').read_text(encoding='utf-8'))


def digest(array, dtype='<u2'):
    return sha256(np.asarray(array, dtype=dtype).tobytes()).hexdigest()


@pytest.fixture(scope='module')
def engine():
    return Engine.load()


@pytest.mark.parametrize('fixture', RECORD['fixtures'], ids=lambda row: row['space'] + ':' + row['case'])
def test_original_firmware_final_tables(engine, fixture):
    """Expected digests are taken from original Make, not generated by gold.py."""
    _, _, _, (full, diff, _) = _calculate(engine, fixture['settings'], fixture['space'])
    camera = gold_camera(engine, fixture['settings'], fixture['space'])
    assert digest(full) == fixture['full_u16_sha256']
    assert digest(diff, '<u8') == fixture['diff_u64_sha256']
    assert digest(camera.curves) == fixture['rgb4096_u16_sha256']
    assert digest(camera.cc0, '<i2') == fixture['cc0_i16_sha256']
    assert digest(camera.yc, '<i2') == fixture['yc_i16_sha256']
    assert camera.curves.shape == (3, 4096) and camera.curve_max == 1023


def test_interpolation_signed_truncation_and_u16_boundaries():
    table = np.array([1000 - 3*np.arange(256)])
    values = [0,1,63,64,16319,16320,16384,65535]
    assert _interpolate(table, values).tolist() == [[1000,1000,998,997,236,235,235,235]]


def test_delta_saturation_negative_and_last_interval():
    values = np.array([[0,16384,0] + [160]*253])
    full, words, response = _hardware(values, 'srgb')
    assert full[0,:3].tolist() == [0,1023,0]
    assert response[0,:16].tolist() == (15*np.arange(16)).tolist()
    assert response[0,16:32].tolist() == [1023]*16
    assert int(words[0,-1]) == 0
    assert response[0,-16:].tolist() == [10]*16


def test_physical_rgb_channel_mapping(engine):
    camera = gold_camera(engine, {})
    # The old public register reader calls physical R/G/B "rgb"/"r"/"g".
    assert camera.curves[:,0].tolist() == [0,0,96]
    assert camera.notes['runtime'] == {} and runtime_spec() == {}
    assert np.isfinite(camera.render(np.array([[0,0,0],[0.18,0.18,0.18],[1,1,1]]))).all()


@pytest.mark.parametrize('settings', [{'key':5},{'hue':-5},{'key':True},{'key':0.5},{'unknown':0},[],None])
def test_invalid_settings_rejected(engine, settings):
    with pytest.raises(ValueError):
        gold_camera(engine, settings)


@pytest.mark.parametrize('runtime', [{'exposure_gain':8192},{'custom_gamma':False},[],0,''])
def test_unknown_runtime_rejected(engine, runtime):
    with pytest.raises(ValueError):
        gold_camera(engine, {}, runtime=runtime)


def test_unknown_color_space_rejected(engine):
    with pytest.raises(ValueError):
        gold_camera(engine, {}, 'display-p3')


